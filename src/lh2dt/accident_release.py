"""Native accident-release histories for the LH2 digital-twin components.

The normal-state component APIs in :mod:`lh2dt` are intentionally kept
separate from the accident boundary.  This module provides the explicit
boundary contract used by PRISM.  Every history is generated by the owning
component's thermodynamic/hydraulic methods and carries the requested event,
port, time step, termination basis, and mass/energy ledger.

The defaults are diagnostic and synthetic.  A native method therefore does
not imply a qualified frequency or field-calibrated result.
"""
from __future__ import annotations

import math
from collections.abc import Mapping
from typing import Any


EXPORT_SCHEMA = "prism.external_accident_history.v1"


def _number(request: Mapping[str, Any], key: str, default: float, *, positive: bool = False) -> float:
    value = request.get(key, default)
    if isinstance(value, bool):
        raise ValueError(f"{key} must be numeric")
    try:
        value = float(value)
    except (TypeError, ValueError) as error:
        raise ValueError(f"{key} must be numeric") from error
    if not math.isfinite(value) or (positive and value <= 0.0):
        raise ValueError(f"{key} must be finite and {'positive' if positive else 'non-negative'}")
    return value


def _identity(request: Mapping[str, Any]) -> dict[str, Any]:
    for key in ("event_id", "component_id", "port_id"):
        if not isinstance(request.get(key), str) or not request[key].strip():
            raise ValueError(f"{key} must be a non-empty string")
    horizon = _number(request, "horizon_s", 0.1, positive=True)
    step = _number(request, "time_step_s", min(0.05, horizon), positive=True)
    if step > horizon:
        raise ValueError("time_step_s must not exceed horizon_s")
    ambient_pressure = _number(request, "ambient_pressure_pa_abs", 101325.0, positive=True)
    ambient_temperature = _number(request, "ambient_temperature_k", 288.15, positive=True)
    opening_diameter = request.get("failure_opening_diameter_m")
    if opening_diameter is None:
        area = _number(request, "effective_area_m2", 1.0e-6, positive=True)
        opening_diameter = math.sqrt(4.0 * area / math.pi)
    else:
        opening_diameter = _number(request, "failure_opening_diameter_m", 1.0e-3, positive=True)
        area = math.pi * opening_diameter**2 / 4.0
    return {
        "event_id": request["event_id"],
        "component_id": request["component_id"],
        "port_id": request["port_id"],
        "horizon_s": horizon,
        "time_step_s": step,
        "ambient_pressure_pa_abs": ambient_pressure,
        "ambient_temperature_k": ambient_temperature,
        "failure_opening_diameter_m": opening_diameter,
        "effective_area_m2": area,
        "provider_source_digest": request.get("provider_source_digest", "0" * 64),
        "state_snapshot_digest": request.get("state_snapshot_digest"),
    }


def _source_digest(identity: Mapping[str, Any]) -> str:
    value = identity.get("provider_source_digest")
    if not isinstance(value, str) or len(value) != 64:
        raise ValueError("provider_source_digest must be a 64-character digest")
    return value


def _step_gas(time_s: float, mass_flow: float, state: Any, area: float, *, area_provenance: str) -> dict[str, Any]:
    density = max(float(state.density_kg_m3), 1.0e-12)
    velocity = mass_flow / (density * area) if mass_flow > 0.0 else 0.0
    throat_pressure = max(1.0e3, min(float(state.pressure_Pa) * 0.8, float(state.pressure_Pa) * (1.0 - 1.0e-9)))
    return {
        "time_s": float(time_s),
        "mass_flow_kg_s": float(max(0.0, mass_flow)),
        "pressure_pa_abs": float(state.pressure_Pa),
        "specific_enthalpy_j_kg": float(state.specific_enthalpy_J_kg),
        "temperature_k": float(state.temperature_K),
        "density_kg_m3": float(state.density_kg_m3),
        "effective_area_m2": float(area),
        "velocity_m_s": float(velocity),
        "area_provenance": area_provenance,
        "velocity_origin": "mass_continuity_from_declared_area",
        "provider_source_state": {
            "source_pressure_pa_abs": float(state.pressure_Pa),
            "source_temperature_k": float(state.temperature_K),
            "source_density_kg_m3": float(state.density_kg_m3),
            "source_specific_enthalpy_j_kg": float(state.specific_enthalpy_J_kg),
            "source_specific_entropy_j_kgk": float(state.specific_entropy_J_kgK),
            "throat_pressure_pa_abs": throat_pressure,
            "provider_source_state_provenance": "native component thermodynamic state and explicit isentropic throat-pressure anchor",
        },
    }


def _step_liquid(time_s: float, mass_flow: float, state: Any) -> dict[str, Any]:
    flow = float(max(0.0, mass_flow))
    return {
        "time_s": float(time_s),
        "total_mass_flow_kg_s": flow,
        "gas_mass_flow_kg_s": 0.0,
        "ground_liquid_mass_flow_kg_s": flow,
        "airborne_liquid_mass_flow_kg_s": 0.0,
        "specific_enthalpy_j_kg": float(state.specific_enthalpy_J_kg),
        "droplet_class_outcomes": [{
            "ground_liquid_mass_flow_kg_s": flow,
            "airborne_liquid_mass_flow_kg_s": 0.0,
            "flight_time_s": 0.0,
            "impact_position_m": [0.0, 0.0, 0.0],
            "droplet_diameter_m": 0.001,
        }],
    }


def _response(model: Any, identity: Mapping[str, Any], *, steps: list[dict[str, Any]],
              duration: float, available_mass: float, cumulative_mass: float,
              cumulative_energy: float, phase: str, area_provenance: str,
              termination_basis: str, termination_provenance: str,
              metadata: Mapping[str, Any] | None = None) -> dict[str, Any]:
    if not steps:
        raise ValueError("native accident history must contain at least one interval")
    properties = getattr(model, "properties", None)
    if properties is None and hasattr(model, "valve"):
        properties = getattr(model.valve, "properties", None)
    fluid = getattr(properties, "fluid", "Hydrogen")
    data: dict[str, Any] = {
        "event_kind": "accidental_leak",
        "event_id": identity["event_id"],
        "component_id": identity["component_id"],
        "port_id": identity["port_id"],
        "duration_s": float(duration),
        "available_mass_kg": float(max(available_mass, 1.0e-12)),
        "cumulative_mass_out_kg": float(max(0.0, cumulative_mass)),
        "termination_basis": termination_basis,
        "termination_provenance": termination_provenance,
        "upstream_service": "LH2",
        "fluid": "Hydrogen" if fluid not in {"Hydrogen", "ParaHydrogen"} else fluid,
        "property_basis": {
            "fluid": "Hydrogen" if fluid not in {"Hydrogen", "ParaHydrogen"} else fluid,
            "backend": "CoolProp-HEOS",
            "energy_reference": f"CoolProp-HEOS:{fluid if fluid in {'Hydrogen', 'ParaHydrogen'} else 'Hydrogen'}:native",
        },
        "steps": steps,
        "provider_meta": dict(metadata or {}),
    }
    if phase == "gas":
        data.update({
            "phase_basis": "gas",
            "cumulative_static_enthalpy_out_j": float(cumulative_energy),
        })
    else:
        data.update({
            "phase_basis": "liquid",
            "reference_area_m2": float(identity["effective_area_m2"]),
            "reference_area_provenance": area_provenance,
            "cumulative_specific_enthalpy_out_j": float(cumulative_energy),
            "droplet_partition_provenance": "native component outlet; no airborne-liquid promotion",
        })
    response = {
        "provider_export_schema": EXPORT_SCHEMA,
        "provider_model": f"lh2dt.{type(model).__name__}",
        "provider_source_digest": _source_digest(identity),
        "data": data,
    }
    snapshot_digest = identity.get("state_snapshot_digest")
    if snapshot_digest is not None:
        response["provider_state_snapshot_digest"] = snapshot_digest
    return response


def _source_state(model: Any, request: Mapping[str, Any]) -> Any:
    properties = getattr(model, "properties", None)
    if properties is None and hasattr(model, "valve"):
        properties = getattr(model.valve, "properties", None)
    if properties is None:
        raise ValueError(f"{type(model).__name__} does not expose a property backend")
    pressure = _number(request, "source_pressure_pa_abs", request.get("initial_pressure_pa_abs", 101500.0), positive=True)
    if request.get("initial_quality") is not None:
        quality = _number(request, "initial_quality", 0.0)
        if not 0.0 <= quality <= 1.0:
            raise ValueError("initial_quality must lie in [0, 1]")
        liquid = properties.saturated_liquid(pressure)
        vapor = properties.saturated_vapor(pressure)
        enthalpy = liquid.specific_enthalpy_J_kg + quality * (
            vapor.specific_enthalpy_J_kg - liquid.specific_enthalpy_J_kg
        )
        return properties.from_ph(pressure, enthalpy)
    temperature = _number(request, "source_temperature_k", request.get("initial_temperature_k", 300.0), positive=True)
    return properties.from_pT(pressure, temperature)


def export_dynamic_pipe(model: Any, request: Mapping[str, Any]) -> dict[str, Any]:
    identity = _identity(request)
    isolation_time = request.get("isolation_time_s")
    if isolation_time is not None:
        isolation_time = _number(request, "isolation_time_s", 0.0, positive=True)
        if isolation_time > identity["horizon_s"]:
            raise ValueError("isolation_time_s must not exceed horizon_s")
    post_isolation_observation = request.get("post_isolation_observation_s")
    if post_isolation_observation is not None:
        post_isolation_observation = _number(
            request, "post_isolation_observation_s", 0.0, positive=False
        )
    source = _source_state(model, request)
    initial = model.initialize(source, wall_temperature_K=_number(request, "wall_temperature_k", source.temperature_K, positive=True))
    ambient = model.properties.from_pT(identity["ambient_pressure_pa_abs"], identity["ambient_temperature_k"])
    state = initial
    available = float(initial.mass_kg)
    rows: list[dict[str, Any]] = []
    cumulative_mass = cumulative_mass_in = cumulative_energy = elapsed = 0.0
    release_horizon = identity["horizon_s"] if isolation_time is None else isolation_time
    while elapsed < release_horizon - 1.0e-12 and state.mass_kg > 1.0e-12:
        dt = min(identity["time_step_s"], release_horizon - elapsed)
        current = model.thermo(state)
        # The explicit RK4 state must not cross zero inventory.  Reduce only
        # this provider interval when a deliberately large diagnostic step
        # would do so; the model equations and boundary flow remain native.
        trial_dt = dt
        while True:
            try:
                result = model.step(state, current, ambient, trial_dt)
                break
            except ValueError as error:
                if "non-positive mass" not in str(error) or trial_dt <= 1.0e-6:
                    raise
                trial_dt *= 0.5
        dt = trial_dt
        # ``derivative`` is evaluated at the final RK4 state.  It is not the
        # interval-average outlet flow.  Use the RK4-weighted flux returned by
        # the step result so the provider mass ledger closes with the finite
        # volume state, including any upstream feed before isolation.
        interval_mass_in = max(0.0, float(result.integrated_mass_flow_in_kg_s)) * dt
        interval_mass_out = max(0.0, float(result.integrated_mass_flow_out_kg_s)) * dt
        mass_flow = interval_mass_out / dt
        liquid_mode = request.get("source_mode") == "two_phase" or request.get("initial_quality") is not None
        rows.append(_step_liquid(elapsed, mass_flow, current) if liquid_mode else _step_gas(elapsed, mass_flow, current, identity["effective_area_m2"], area_provenance="native DynamicHEMPipe outlet area"))
        cumulative_mass += interval_mass_out
        cumulative_mass_in += interval_mass_in
        cumulative_energy += interval_mass_out * float(current.specific_enthalpy_J_kg)
        elapsed += dt
        state = result.state
        if mass_flow <= 0.0 and abs(float(result.integrated_mass_flow_out_kg_s)) <= 1.0e-12:
            break
    phase = "liquid" if request.get("source_mode") == "two_phase" or request.get("initial_quality") is not None else "gas"
    reached_isolation = (
        isolation_time is not None
        and abs(elapsed - isolation_time) <= 1.0e-10
        and state.mass_kg > 1.0e-12
    )
    termination_basis = "reviewed_isolation_success" if reached_isolation else "synthetic_diagnostic_horizon"
    termination_provenance = (
        "native DynamicHEMPipe finite-volume state advanced to the provider isolation boundary; "
        "outlet release stopped at isolation_time_s"
        if reached_isolation
        else "native DynamicHEMPipe finite-volume state advanced to the declared diagnostic horizon"
    )
    mass_balance_residual = float(state.mass_kg + cumulative_mass - available - cumulative_mass_in)
    return _response(model, identity, steps=rows, duration=elapsed, available_mass=available,
                     cumulative_mass=cumulative_mass, cumulative_energy=cumulative_energy,
                     phase=phase, area_provenance="native DynamicHEMPipe outlet area",
                     termination_basis=termination_basis,
                     termination_provenance=termination_provenance,
                     metadata={
                         "initial_mass_kg": available,
                         "final_mass_kg": float(state.mass_kg),
                         "cumulative_mass_in_kg": float(cumulative_mass_in),
                         "residual_mass_kg": mass_balance_residual,
                         "mass_balance_residual_kg": mass_balance_residual,
                         "isolation_time_s": isolation_time,
                         "post_isolation_observation_s": post_isolation_observation,
                         "isolation_success": reached_isolation,
                     })


def export_dynamic_thermal(model: Any, request: Mapping[str, Any]) -> dict[str, Any]:
    identity = _identity(request)
    source = _source_state(model, request)
    initial = model.initialize(source, wall_temperature_K=_number(request, "wall_temperature_k", source.temperature_K, positive=True))
    ambient = model.properties.from_pT(identity["ambient_pressure_pa_abs"], identity["ambient_temperature_k"])
    from .valve import Valve
    valve = Valve(identity["effective_area_m2"], _number(request, "discharge_coefficient", 0.8), model.properties, allow_reverse=False)
    state = initial
    available = float(initial.mass_kg)
    rows: list[dict[str, Any]] = []
    cumulative_mass = cumulative_energy = elapsed = 0.0
    while elapsed < identity["horizon_s"] - 1.0e-12 and state.mass_kg > 1.0e-12:
        dt = min(identity["time_step_s"], identity["horizon_s"] - elapsed)
        current = model.thermo(state)
        hydraulic = valve.evaluate(current, ambient)
        mass_flow = min(max(0.0, float(hydraulic.mass_flow_kg_s)), state.mass_kg / dt)
        rows.append(_step_gas(elapsed, mass_flow, current, identity["effective_area_m2"], area_provenance="native dynamic control-volume outlet area"))
        cumulative_mass += mass_flow * dt
        cumulative_energy += mass_flow * dt * float(current.specific_enthalpy_J_kg)
        result = model.step(state, current, 0.0, mass_flow, dt, ambient_temperature_K=identity["ambient_temperature_k"])
        state = result.state
        elapsed += dt
    return _response(model, identity, steps=rows, duration=elapsed, available_mass=available,
                     cumulative_mass=cumulative_mass, cumulative_energy=cumulative_energy,
                     phase="gas", area_provenance="native dynamic control-volume outlet area",
                     termination_basis="inventory_depletion" if state.mass_kg <= 1.0e-12 else "synthetic_diagnostic_horizon",
                     termination_provenance="native dynamic control-volume state and RK4 mass/energy ledger",
                     metadata={"initial_mass_kg": available, "final_mass_kg": float(state.mass_kg), "residual_mass_kg": float(state.mass_kg + cumulative_mass - available)})


def export_valve(model: Any, request: Mapping[str, Any]) -> dict[str, Any]:
    identity = _identity(request)
    source = _source_state(model, request)
    properties = getattr(model.valve, "properties", None)
    if properties is None:
        raise ValueError("native valve does not expose a property backend")
    ambient = properties.from_pT(identity["ambient_pressure_pa_abs"], identity["ambient_temperature_k"])
    available = _number(request, "available_mass_kg", 1.0, positive=True)
    state = source
    dt = identity["time_step_s"]
    rows: list[dict[str, Any]] = []
    cumulative_mass = cumulative_energy = elapsed = 0.0
    target = _number(request, "target_opening", 1.0)
    if hasattr(model, "set_target_opening"):
        model.set_target_opening(target)
    choked = 0
    while elapsed < identity["horizon_s"] - 1.0e-12 and cumulative_mass < available - 1.0e-12:
        interval = min(dt, identity["horizon_s"] - elapsed)
        if hasattr(model, "advance"):
            model.advance(interval)
        result = model.evaluate(state, ambient)
        mass_flow = min(max(0.0, float(result.mass_flow_kg_s)), (available - cumulative_mass) / interval)
        rows.append(_step_gas(elapsed, mass_flow, state, identity["effective_area_m2"], area_provenance="native valve effective opening area"))
        cumulative_mass += mass_flow * interval
        cumulative_energy += mass_flow * interval * float(state.specific_enthalpy_J_kg)
        choked += int(bool(getattr(result, "choked", False)))
        elapsed += interval
    return _response(model, identity, steps=rows, duration=elapsed, available_mass=available,
                     cumulative_mass=cumulative_mass, cumulative_energy=cumulative_energy,
                     phase="gas", area_provenance="native valve effective opening area",
                     termination_basis="inventory_depletion" if cumulative_mass >= available - 1.0e-12 else "synthetic_diagnostic_horizon",
                     termination_provenance="native ValveResult with explicit stroke-limited actuator and bounded upstream reserve",
                     metadata={"initial_source_phase": state.phase, "final_opening": getattr(model, "opening", None), "choked_intervals": choked, "residual_mass_kg": available - cumulative_mass})


def export_vent_stack(model: Any, request: Mapping[str, Any]) -> dict[str, Any]:
    identity = _identity(request)
    source = _source_state(model, request)
    ambient = model.properties.from_pT(identity["ambient_pressure_pa_abs"], identity["ambient_temperature_k"])
    available = _number(request, "available_mass_kg", 1.0, positive=True)
    hydraulic = model.evaluate(source, ambient)
    dt = identity["time_step_s"]
    rows: list[dict[str, Any]] = []
    cumulative_mass = cumulative_energy = elapsed = 0.0
    while elapsed < identity["horizon_s"] - 1.0e-12 and cumulative_mass < available - 1.0e-12:
        interval = min(dt, identity["horizon_s"] - elapsed)
        mass_flow = min(max(0.0, float(hydraulic.mass_flow_kg_s)), (available - cumulative_mass) / interval)
        rows.append(_step_gas(elapsed, mass_flow, source, identity["effective_area_m2"], area_provenance="native VentStack hydraulic outlet area"))
        cumulative_mass += mass_flow * interval
        cumulative_energy += mass_flow * interval * float(source.specific_enthalpy_J_kg)
        elapsed += interval
    return _response(model, identity, steps=rows, duration=elapsed, available_mass=available,
                     cumulative_mass=cumulative_mass, cumulative_energy=cumulative_energy,
                     phase="gas", area_provenance="native VentStack hydraulic outlet area",
                     termination_basis="synthetic_diagnostic_horizon",
                     termination_provenance="operator-declared bounded VentStack horizon; upstream reserve remains explicit",
                     metadata={"hydraulic": {"mass_flow_kg_s": float(hydraulic.mass_flow_kg_s), "reynolds_number": float(hydraulic.reynolds_number), "pressure_drop_pa": float(hydraulic.pressure_drop_Pa)}, "residual_mass_kg": available - cumulative_mass})


def export_pump(model: Any, request: Mapping[str, Any]) -> dict[str, Any]:
    identity = _identity(request)
    source = _source_state(model, request)
    available = _number(request, "available_mass_kg", 1.0, positive=True)
    rise = _number(request, "pump_pressure_rise_pa", 100000.0, positive=True)
    target = model.properties.from_pT(identity["ambient_pressure_pa_abs"] + rise, identity["ambient_temperature_k"])
    hydraulic = model.evaluate(source, target)
    dt = identity["time_step_s"]
    rows: list[dict[str, Any]] = []
    cumulative_mass = cumulative_energy = elapsed = 0.0
    while elapsed < identity["horizon_s"] - 1.0e-12 and cumulative_mass < available - 1.0e-12:
        interval = min(dt, identity["horizon_s"] - elapsed)
        mass_flow = min(max(0.0, float(hydraulic.mass_flow_kg_s)), (available - cumulative_mass) / interval)
        rows.append(_step_liquid(elapsed, mass_flow, source))
        cumulative_mass += mass_flow * interval
        cumulative_energy += mass_flow * interval * float(source.specific_enthalpy_J_kg)
        elapsed += interval
    return _response(model, identity, steps=rows, duration=elapsed, available_mass=available,
                     cumulative_mass=cumulative_mass, cumulative_energy=cumulative_energy,
                     phase="liquid", area_provenance="native MappedPump H-Q-N outlet",
                     termination_basis="synthetic_diagnostic_horizon",
                     termination_provenance="operator-declared bounded MappedPump feed-through horizon; upstream reserve remains explicit",
                     metadata={"pump_operating_point": {"mass_flow_kg_s": float(hydraulic.mass_flow_kg_s), "pressure_rise_pa": float(hydraulic.pressure_rise_Pa), "map_head_pressure_rise_pa": float(hydraulic.map_head_pressure_rise_Pa), "map_limited": bool(hydraulic.map_limited), "cavitation_margin_m": hydraulic.cavitation_margin_m}, "residual_mass_kg": available - cumulative_mass})


def export_layered_tank(model: Any, request: Mapping[str, Any]) -> dict[str, Any]:
    identity = _identity(request)
    from .layered_network import LayeredTankNetworkSimulator, LayeredTankPort
    from .network import SteadyNetwork
    from .valve import CommandedValve, Valve
    pressure = _number(request, "initial_pressure_pa_abs", 205000.0, positive=True)
    liquid_fraction = _number(request, "liquid_volume_fraction", 0.2)
    state = model.initialize_saturated(pressure, liquid_fraction)
    initial_mass = float(model.total_mass_kg(state))
    network = SteadyNetwork(model.properties)
    network.add_boundary("liquid_port", model.thermo(state).liquid[0])
    network.add_boundary("atmospheric_sink", model.properties.from_pT(identity["ambient_pressure_pa_abs"], identity["ambient_temperature_k"]))
    valve = CommandedValve(Valve(identity["effective_area_m2"], _number(request, "discharge_coefficient", 0.8), model.properties, pressure_samples=12, allow_reverse=False), initial_opening=1.0)
    network.add_link("liquid_out", "liquid_port", "atmospheric_sink", valve, source_port_id="TANK:L0", target_port_id="ATMOSPHERE:IN")
    simulator = LayeredTankNetworkSimulator(model, network, ports=(LayeredTankPort("liquid_port", "liquid", 0),), ambient_temperature_K=identity["ambient_temperature_k"])
    elapsed = cumulative_mass = cumulative_energy = 0.0
    rows: list[dict[str, Any]] = []
    target_release = _number(request, "target_release_kg", min(1.0e-4, initial_mass * 0.1), positive=True)
    threshold = max(0.0, initial_mass - target_release)
    while elapsed < identity["horizon_s"] - 1.0e-12 and model.total_mass_kg(state) > threshold + 1.0e-12:
        dt = min(identity["time_step_s"], identity["horizon_s"] - elapsed)
        result = simulator.simulate(state, duration_s=dt, time_step_s=dt)[0]
        flow = result.network_solution.link_flows["liquid_out"]
        boundary_mass = max(0.0, -float(result.tank.cumulative_boundary_mass_kg))
        boundary_energy = max(0.0, -float(result.tank.cumulative_boundary_energy_J))
        interval_mass = boundary_mass
        interval_energy = boundary_energy
        average_flow = interval_mass / dt
        current = result.tank.thermo.liquid[0]
        rows.append(_step_liquid(elapsed, average_flow, current))
        cumulative_mass += interval_mass
        cumulative_energy += interval_energy
        state = result.tank.state
        elapsed += dt
    basis = "inventory_depletion" if model.total_mass_kg(state) <= threshold + 1.0e-12 else "synthetic_diagnostic_horizon"
    return _response(model, identity, steps=rows, duration=elapsed, available_mass=initial_mass,
                     cumulative_mass=cumulative_mass, cumulative_energy=cumulative_energy,
                     phase="liquid", area_provenance="native LayeredTank liquid outlet area",
                     termination_basis=basis,
                     termination_provenance="native LayeredTank state, network valve flow, and integrated boundary mass/energy ledger",
                     metadata={"initial_mass_kg": initial_mass, "final_mass_kg": float(model.total_mass_kg(state)), "target_release_kg": target_release, "residual_mass_kg": float(model.total_mass_kg(state) + cumulative_mass - initial_mass)})


def export_accident_history(model: Any, request: Mapping[str, Any]) -> dict[str, Any]:
    """Dispatch an explicit native accident history for one component."""
    if not isinstance(request, Mapping):
        raise TypeError("accident release request must be a mapping")
    name = type(model).__name__
    if name == "LayeredTank":
        return export_layered_tank(model, request)
    if name == "DynamicHEMPipe":
        return export_dynamic_pipe(model, request)
    if name in {"DynamicVaporizer", "DynamicReliquefier"}:
        return export_dynamic_thermal(model, request)
    if name == "StrokeLimitedCommandedValve":
        return export_valve(model, request)
    if name == "VentStack":
        return export_vent_stack(model, request)
    if name == "MappedPump":
        return export_pump(model, request)
    raise TypeError(f"native accident export is not implemented for {name}")


